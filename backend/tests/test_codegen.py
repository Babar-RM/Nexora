# 3. Expressions & Precedence (RFC-0008 §3.4)
# =============================================================================


class TestExpressionsAndPrecedence:
    """Verify operator precedence, associativity, and comparison-chaining prevention."""

    def test_comparison_chaining_trap_avoided(self) -> None:
        # MiniLang: a == b == c is (a == b) == c (all bools)
        src = """
        make a = yes;
        make b = yes;
        make c = yes;
        show(a == b == c);
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)
        # RFC-0008 §3.4: parent and child both level 4 must be parenthesized
        assert "(a == b) == c" in result.code

    def test_comparison_chaining_complex(self) -> None:
        src = """
        make a = 1;
        make b = 2;
        make c = 3;
        make d = 4;
        show((a < b) == (c < d));
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)
        assert "(a < b) == (c < d)" in result.code

    def test_right_associativity_subtraction_and_division(self) -> None:
        # a - (b - c) must keep parens, (a - b) - c does not need inner parens
        src = """
        make a = 10;
        make b = 5;
        make c = 2;
        show(a - (b - c));
        show((a - b) - c);
        show(a / (b * c));
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)
        assert "a - (b - c)" in result.code
        assert "a - b - c" in result.code
        assert "a / (b * c)" in result.code

    def test_unary_nesting_parens(self) -> None:
        src = """
        make x = 5;
        show(-(-x));
        make b = yes;
        show(not (not b));
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)
        assert "-(-x)" in result.code
        assert "not (not b)" in result.code

    def test_logical_operator_spellings(self) -> None:
        src = """
        make a = yes;
        make b = no;
        show(a both b);
        show(a either b);
        show(not a);
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)
        assert "a and b" in result.code
        assert "a or b" in result.code
        assert "not a" in result.code


