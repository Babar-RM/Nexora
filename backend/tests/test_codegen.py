# 2. Statement Mapping Tests (RFC-0008 §3.3)
# =============================================================================


class TestStatementMapping:
    """Verify correct generation of MiniLang statements to Python 3.10+."""

    def test_make_and_assign(self) -> None:
        src = """
        make x = 10;
        x = 20;
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)
        assert "x = 10\n" in result.code
        assert "x = 20\n" in result.code

    def test_ask_statements(self) -> None:
        src = """
        ask s: string;
        ask i: int;
        ask f: float;
        """
        ast = compile_source_to_ast(src)
        result = generate_python(ast)
        assert "s = input()\n" in result.code
        assert "i = int(input())\n" in result.code
        assert "f = float(input())\n" in result.code

    def test_when_elif_else_flattening(self) -> None:
        src = """
        make age = 20;
        when (age < 13) {
            show("child");
        } otherwise when (age < 20) {
            show("teen");
        } otherwise {
            show("adult");
        }
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)
        assert "if age < 13:\n" in result.code
        assert "elif age < 20:\n" in result.code
        assert "else:\n" in result.code

    def test_during_loop_stop_skip(self) -> None:
        src = """
        make i = 0;
        during (i < 10) {
            when (i == 3) {
                skip;
            }
            when (i == 8) {
                stop;
            }
            i = i + 1;
        }
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)
        assert "while i < 10:\n" in result.code
        assert "continue\n" in result.code
        assert "break\n" in result.code

    def test_empty_suite_emits_pass(self) -> None:
        src = """
        task noop() {
        }
        when (yes) {
        }
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)
        assert "def noop():\n    pass\n" in result.code
        assert "if True:\n    pass\n" in result.code


