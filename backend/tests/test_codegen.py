"""Comprehensive unit, golden, and property tests for Python Code Generator (RFC-0008).

Governed by RFC-0008 §7, this test suite verifies:
1. Output layout, header, prelude emission (only when show is used)
2. Statement mappings (make, assign, ask, when/elif/else, during, give, stop, skip, expr stmts)
3. Expression parenthesization and Python comparison-chaining trap avoidance
4. int -> float widening (literals, variables, expressions, call args, returns)
5. Identifier mangling for Python keywords and builtins (deterministic collision resolution)
6. Line map invariants (length == code.count('\\n')) and source-line fidelity
7. Whitelist AST validator (accepts safe code, rejects unauthorized AST nodes or imports)
8. Golden file comparisons (tests/golden/factorial.py.expected, hello.py.expected)
9. Determinism: identical input AST produces byte-identical generated Python
"""

from __future__ import annotations

from pathlib import Path

import pytest

from nexora.ast_nodes import Program
from nexora.codegen_python import (
    generate_python,
    validate_generated_python,
)
from nexora.errors import InternalCompilerError
from nexora.lexer import Lexer
from nexora.optimizer import optimize_program
from nexora.parser import Parser
from nexora.semantic import SemanticAnalyzer

GOLDEN_DIR = Path(__file__).parent / "golden"
FIXTURES_DIR = Path(__file__).parent / "fixtures" / "valid"


def compile_source_to_ast(source: str, optimize: bool = True) -> Program:
    """Helper: Lex, parse, type-check, and optionally optimize MiniLang source to AST."""
    tokens = Lexer(source).tokenize()
    parse_result = Parser(tokens).parse()
    analyzer = SemanticAnalyzer()
    analyzer.analyze(parse_result.program)
    ast = parse_result.program
    if optimize:
        ast, _ = optimize_program(ast)
    return ast


# =============================================================================
# 1. Output Layout and Prelude Tests (RFC-0008 §3.2)
# =============================================================================


class TestCodegenLayoutAndPrelude:
    """Verify output header, task hoisting, and conditional prelude inclusion."""

    def test_header_always_present_without_timestamps(self) -> None:
        src = "make x = 1;"
        ast = compile_source_to_ast(src)
        result = generate_python(ast)

        lines = result.code.splitlines()
        assert lines[0] == "# Generated by Nexora (MiniLang -> Python). Do not edit."
        assert result.code.endswith("\n")

    def test_prelude_emitted_only_when_show_is_used(self) -> None:
        src_no_show = "make x = 1;"
        ast_no_show = compile_source_to_ast(src_no_show)
        res_no_show = generate_python(ast_no_show)
        assert "def __nx_show" not in res_no_show.code

        src_with_show = "show(42);"
        ast_with_show = compile_source_to_ast(src_with_show)
        res_with_show = generate_python(ast_with_show)
        assert "def __nx_show(value):" in res_with_show.code
        assert 'print("true" if value else "false")' in res_with_show.code

    def test_tasks_hoisted_before_top_level_statements(self) -> None:
        src = """
        show(get_val());
        task get_val(): int {
            give 100;
        }
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)

        def_pos = result.code.find("def get_val():")
        call_pos = result.code.find("__nx_show(get_val())")
        assert def_pos != -1
        assert call_pos != -1
        assert def_pos < call_pos


