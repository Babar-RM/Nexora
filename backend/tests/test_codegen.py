# 7. Whitelist Validator Tests (RFC-0008 §3.9)
# =============================================================================


class TestWhitelistValidator:
    """Ensure generated-code validator rejects unsafe AST nodes."""

    def test_validator_accepts_clean_generated_code(self) -> None:
        code = "def add(a, b):\n    return a + b\nx = 10\nprint(add(x, 20))\n"
        validate_generated_python(code)

    def test_validator_rejects_import_statements(self) -> None:
        with pytest.raises(InternalCompilerError, match="Disallowed AST node"):
            validate_generated_python("import os\n")

    def test_validator_rejects_attribute_access(self) -> None:
        with pytest.raises(
            InternalCompilerError,
            match="Call target must be a simple Name|Disallowed AST node",
        ):
            validate_generated_python("os.system('ls')\n")
        with pytest.raises(InternalCompilerError, match="Disallowed AST node"):
            validate_generated_python("x = a.b\n")

    def test_validator_rejects_lambda_and_try(self) -> None:
        with pytest.raises(InternalCompilerError, match="Disallowed AST node"):
            validate_generated_python("f = lambda x: x + 1\n")
        with pytest.raises(InternalCompilerError, match="Disallowed AST node"):
            validate_generated_python("try:\n    pass\nexcept:\n    pass\n")


