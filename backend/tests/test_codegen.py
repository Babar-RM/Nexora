# 5. Identifier Mangling (RFC-0008 §3.6)
# =============================================================================


class TestIdentifierMangling:
    """Verify renaming of Python keywords and builtins with collision avoidance."""

    def test_python_keywords_and_builtins_mangled(self) -> None:
        src = """
        make def = 1;
        make class = 2;
        make print = 3;
        show(def + class + print);
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)

        assert "def_ = 1" in result.code
        assert "class_ = 2" in result.code
        assert "print_ = 3" in result.code
        assert "def_" in result.names
        assert result.names["def_"] == "def"
        assert result.names["class_"] == "class"
        assert result.names["print_"] == "print"

    def test_collision_chain_mangling(self) -> None:
        # print collides with builtin, and print_ already exists in user source
        src = """
        make print = 10;
        make print_ = 20;
        show(print + print_);
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)

        # print becomes print__, leaving print_ uncollided
        assert "print__ = 10" in result.code
        assert "print_ = 20" in result.code
        assert result.names["print__"] == "print"


