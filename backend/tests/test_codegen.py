# 4. Widening Tests (RFC-0008 §3.5)
# =============================================================================


class TestWidening:
    """Verify int -> float widening preserves semantics."""

    def test_literal_widened_to_float_literal(self) -> None:
        src = "make p: float = 2;"
        ast = compile_source_to_ast(src)
        result = generate_python(ast)
        # Should emit 2.0 directly rather than float(2)
        assert "p = 2.0" in result.code

    def test_expression_widened_with_float_call(self) -> None:
        src = """
        make a = 2;
        make b = 3;
        make p: float = a + b;
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)
        assert "p = float(a + b)" in result.code

    def test_argument_and_return_widening(self) -> None:
        src = """
        task compute(factor: float): float {
            give 42;
        }
        show(compute(5));
        """
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)
        # return widened to 42.0 (int literal)
        assert "return 42.0" in result.code
        # argument widened to 5.0 (int literal)
        assert "compute(5.0)" in result.code


