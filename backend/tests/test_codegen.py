# 6. Line Map Tests (RFC-0008 §3.7)
# =============================================================================


class TestLineMap:
    """Verify line map length, correspondence, and runtime error location."""

    def test_line_map_length_matches_newline_count(self) -> None:
        src = """
        make a = 1;
        make b = 2;
        show(a + b);
        """
        ast = compile_source_to_ast(src)
        result = generate_python(ast)
        assert len(result.line_map) == result.code.count("\n")

    def test_line_map_maps_statements_to_minilang_lines(self) -> None:
        src = "// line 1\n// line 2\nmake x = 42; // line 3\nshow(x);     // line 4\n"
        ast = compile_source_to_ast(src, optimize=False)
        result = generate_python(ast)

        lines = result.code.splitlines()
        for i, line in enumerate(lines):
            minilang_line = result.line_map[i]
            if "x = 42" in line:
                assert minilang_line == 3
            elif "__nx_show(x)" in line:
                assert minilang_line == 4
            elif "def __nx_show" in line or line.startswith("#"):
                assert minilang_line == 0


