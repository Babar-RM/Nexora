# 8. Golden and Determinism Tests (RFC-0008 §3.10, §3.11, §7)
# =============================================================================


class TestGoldenAndDeterminism:
    """Verify exact golden file fidelity and byte-identical determinism."""

    def test_golden_hello(self) -> None:
        mini_path = FIXTURES_DIR / "hello.mini"
        expected_path = GOLDEN_DIR / "hello.py.expected"

        source = mini_path.read_text(encoding="utf-8")
        expected = expected_path.read_text(encoding="utf-8")

        ast = compile_source_to_ast(source, optimize=False)
        result = generate_python(ast)

        assert result.code == expected

    def test_golden_factorial(self) -> None:
        mini_path = FIXTURES_DIR / "factorial.mini"
        expected_path = GOLDEN_DIR / "factorial.py.expected"

        source = mini_path.read_text(encoding="utf-8")
        expected = expected_path.read_text(encoding="utf-8")

        ast = compile_source_to_ast(source, optimize=False)
        result = generate_python(ast)

        assert result.code == expected

    def test_codegen_determinism(self) -> None:
        src = """
        make a = 1;
        make b = 2;
        task add(x: int, y: int): int {
            give x + y;
        }
        show(add(a, b));
        """
        ast1 = compile_source_to_ast(src)
        ast2 = compile_source_to_ast(src)

        res1 = generate_python(ast1)
        res2 = generate_python(ast2)

        # Byte-identical output
        assert res1.code == res2.code
        assert res1.line_map == res2.line_map
        assert res1.names == res2.names
